"""Build kernel2/main.py from src/launcher2.py + src/driver2.py."""
import base64
import json
import os
import py_compile

ROOT = os.path.dirname(os.path.abspath(__file__))

driver = open(os.path.join(ROOT, "src", "driver2.py")).read()
wspio = open(os.path.join(ROOT, "src", "wspio.py")).read()
# the launcher uploads a single file: splice wspio in place of its import
IMPORT_BLOCK = """import sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from wspio import st_load, st_save, bf16_bits, bf16_to_f32, NAMES, L15, L19
"""
assert IMPORT_BLOCK in driver
driver = driver.replace(IMPORT_BLOCK, "")
launcher = open(os.path.join(ROOT, "src", "launcher2.py")).read()
b64 = base64.b64encode((wspio + "\n\n" + driver).encode()).decode()
launcher = launcher.replace("DRIVER_B64 = None", f"DRIVER_B64 = {b64!r}")
assert "DRIVER_B64 = None" not in launcher

out_dir = os.path.join(ROOT, "kernel2")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(
    "# GENERATED by build2.py - do not edit; patch src/ instead\n" + launcher)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)
py_compile.compile(os.path.join(ROOT, "src", "driver2.py"), doraise=True)

kid = os.environ.get("KAGGLE_KERNEL_ID", "mauricew/wsp-s2-variant")
meta = {
    "id": kid,
    "title": kid.split("/")[-1],
    "code_file": "main.py",
    "language": "python",
    "kernel_type": "script",
    "enable_gpu": True,
    "enable_internet": True,
    "is_private": True,
    "dataset_sources": ["mauricew/wsp-s2-materials"],
    "competition_sources": [],
    "kernel_sources": [],
    "model_sources": [],
}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"))
