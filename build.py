"""Build kernel/main.py from src/launcher.py + src/driver.py and sanity-check it.

Also emits kernel/kernel-metadata.json.
"""
import base64
import json
import os
import py_compile
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))

driver = open(os.path.join(ROOT, "src", "driver.py")).read()
launcher = open(os.path.join(ROOT, "src", "launcher.py")).read()

b64 = base64.b64encode(driver.encode()).decode()
launcher = launcher.replace("DRIVER_B64 = None",
                            f"DRIVER_B64 = {b64!r}")
assert "DRIVER_B64 = None" not in launcher

out_dir = os.path.join(ROOT, "kernel")
os.makedirs(out_dir, exist_ok=True)
open(os.path.join(out_dir, "main.py"), "w").write(
    "# GENERATED by build.py - do not edit; patch src/ instead\n" + launcher)
py_compile.compile(os.path.join(out_dir, "main.py"), doraise=True)
py_compile.compile(os.path.join(ROOT, "src", "driver.py"), doraise=True)

meta = {
    "id": os.environ.get("KAGGLE_KERNEL_ID", "mauricew/wsp-s1-baseline"),
    "title": os.environ.get("KAGGLE_KERNEL_ID", "mauricew/wsp-s1-baseline")
             .split("/")[-1],
    "code_file": "main.py",
    "language": "python",
    "kernel_type": "script",
    "enable_gpu": True,
    "enable_internet": True,
    "is_private": True,
    "dataset_sources": [],
    "competition_sources": [],
    "kernel_sources": [],
    "model_sources": [],
}
json.dump(meta, open(os.path.join(out_dir, "kernel-metadata.json"), "w"), indent=1)
print("built", os.path.join(out_dir, "main.py"),
      len(launcher) // 1024, "KB; metadata gpu:", meta["enable_gpu"])
